"""The flat error envelope, the per-code constants, and the exception handlers.

DATABASE_SETUP.md Part 3.0. Written BEFORE the first route, deliberately:
retrofitting an error envelope means auditing every ``raise`` in the codebase.

Every non-2xx response from every route has exactly this body::

    {"error_code": ..., "message": ..., "retryable": ..., "request_id": ...}

FastAPI's default ``{"detail": ...}`` -- and in particular the *list* body it
produces for ``RequestValidationError`` with status 422 -- must never escape.
422 is not in the client's error taxonomy (it would surface as a raw
"Server error (422).") and the default body leaks the internal field paths of
the request model.

``request_id`` is generated by ``RequestIdMiddleware``, held in a ``ContextVar``,
set as the ``X-Request-Id`` header on ALL responses including 2xx, and injected
into the envelope by every handler here.
"""

from __future__ import annotations

import logging
import uuid
from contextvars import ContextVar
from typing import Any, Final

from fastapi import FastAPI, Request
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse
from starlette.exceptions import HTTPException as StarletteHTTPException
from starlette.types import ASGIApp, Message, Receive, Scope, Send

from app.models.enums import ErrorCode
from app.models.responses import ErrorEnvelope

logger = logging.getLogger("tennisform.api")

REQUEST_ID_HEADER: Final[str] = "X-Request-Id"

_request_id_var: ContextVar[str] = ContextVar("request_id", default="")


def current_request_id() -> str:
    """The id of the request being served, or ``""`` outside a request."""
    return _request_id_var.get()


def new_request_id() -> str:
    """A fresh correlation id. 32 hex chars, matching the Part 3.0 example."""
    return uuid.uuid4().hex


