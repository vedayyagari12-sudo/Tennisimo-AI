def is_retryable(code: ErrorCode) -> bool:
    """Per-code constant retryability."""
    return ERROR_RETRYABLE[code]


def http_status_for(code: ErrorCode) -> int:
    """HTTP status for a code that is raised on the HTTP path.

    A job-only code has no HTTP status by design. Reaching here with one means a
    route raised something only a background job should raise, so it is logged
    and degraded to 500 rather than crashing the handler that is already
    handling an error.
    """
    status = ERROR_HTTP_STATUS.get(code)
    if status is None:
        logger.error("job-only ErrorCode %s raised on the HTTP path; sending 500", code.value)
        return 500
    return status


def default_message_for(code: ErrorCode) -> str:
    return ERROR_MESSAGES[code]


class ApiError(Exception):
    """The project's own HTTP error. Carries an ``ErrorCode``, not a ``detail``.

    Preferred over ``HTTPException`` everywhere in this codebase, because the
    envelope needs a machine-readable code and ``HTTPException`` has nowhere to
    put one.
    """

    def __init__(
        self,
        error_code: ErrorCode,
        *,
        message: str | None = None,
        http_status: int | None = None,
        headers: dict[str, str] | None = None,
    ) -> None:
        self.error_code: ErrorCode = error_code
        self.message: str = message if message is not None else default_message_for(error_code)
        self.http_status: int = http_status if http_status is not None else http_status_for(error_code)
        self.retryable: bool = is_retryable(error_code)
        self.headers: dict[str, str] = dict(headers or {})
        super().__init__(f"{error_code.value}: {self.message}")


def envelope_response(
    error_code: ErrorCode,
    message: str,
    http_status: int,
    *,
    headers: dict[str, str] | None = None,
) -> JSONResponse:
    """Build the one and only error body shape."""
    request_id = current_request_id() or new_request_id()
    envelope = ErrorEnvelope(
        error_code=error_code,
        message=message,
        retryable=is_retryable(error_code),
        request_id=request_id,
    )
    out_headers: dict[str, str] = {REQUEST_ID_HEADER: request_id}
    out_headers.update(headers or {})
    return JSONResponse(
        status_code=http_status,
        content=envelope.model_dump(mode="json"),
        headers=out_headers,
    )


