class RequestIdMiddleware:
    """Pure-ASGI middleware assigning and echoing ``X-Request-Id``.

    Pure ASGI rather than ``BaseHTTPMiddleware`` on purpose: ``BaseHTTPMiddleware``
    runs the downstream app in its own task, so the ``ContextVar`` set there is
    not visible to Starlette's ``ServerErrorMiddleware``, which sits UPSTREAM and
    is what invokes the ``Exception`` handler. Staying in the same task context
    keeps ``current_request_id()`` correct in every handler, including the 500 one.

    The ``ContextVar`` is intentionally never reset: each request runs in its own
    task context, so there is nothing to leak into, and resetting on the way out
    would blank the id exactly when an exception is propagating past us.
    """

    def __init__(self, app: ASGIApp) -> None:
        self.app = app

    async def __call__(self, scope: Scope, receive: Receive, send: Send) -> None:
        if scope["type"] != "http":
            await self.app(scope, receive, send)
            return

        request_id = new_request_id()
        _request_id_var.set(request_id)

        async def send_with_request_id(message: Message) -> None:
            if message["type"] == "http.response.start":
                headers: list[tuple[bytes, bytes]] = list(message.get("headers", []))
                key = REQUEST_ID_HEADER.lower().encode("latin-1")
                if not any(name.lower() == key for name, _ in headers):
                    headers.append((key, request_id.encode("latin-1")))
                message = {**message, "headers": headers}
            await send(message)

        await self.app(scope, receive, send_with_request_id)


