async def api_error_handler(request: Request, exc: Exception) -> JSONResponse:
    """``ApiError`` -> the flat envelope with its own code and status."""
    assert isinstance(exc, ApiError)
    logger.info(
        "api_error request_id=%s code=%s status=%s path=%s",
        current_request_id(),
        exc.error_code.value,
        exc.http_status,
        request.url.path,
    )
    return envelope_response(exc.error_code, exc.message, exc.http_status, headers=exc.headers)


async def validation_error_handler(request: Request, exc: Exception) -> JSONResponse:
    """``RequestValidationError`` -> **400 invalid_request**, never a bare 422.

    This is the handler that gets forgotten. Without it a Pydantic failure on
    ``CreateAnalysisRequest`` or ``UploadTicketRequest`` returns FastAPI's 422
    with a list body under ``detail``, which (a) is not in the client's error
    taxonomy and (b) leaks the internal field paths of the request model.

    The per-field detail is logged against ``request_id``, not returned.
    """
    detail: Any = exc.errors() if isinstance(exc, RequestValidationError) else str(exc)
    logger.info(
        "validation_error request_id=%s path=%s detail=%s",
        current_request_id(),
        request.url.path,
        detail,
    )
    return envelope_response(
        ErrorCode.INVALID_REQUEST,
        default_message_for(ErrorCode.INVALID_REQUEST),
        http_status_for(ErrorCode.INVALID_REQUEST),
    )


async def http_exception_handler(request: Request, exc: Exception) -> JSONResponse:
    """Net for anything Starlette raises internally: unknown path (404), 405, ...

    Not a licence to raise ``HTTPException`` from a route -- routes raise
    ``ApiError``. This exists so a 404 on a mistyped URL still comes back in the
    envelope rather than as ``{"detail": "Not Found"}``.
    """
    assert isinstance(exc, StarletteHTTPException)
    if exc.status_code == 401:
        code = ErrorCode.AUTH_INVALID_TOKEN
    elif exc.status_code == 404:
        code = ErrorCode.ANALYSIS_NOT_FOUND if "/analyses/" in request.url.path else ErrorCode.INVALID_REQUEST
    elif 400 <= exc.status_code < 500:
        code = ErrorCode.INVALID_REQUEST
    else:
        code = ErrorCode.INTERNAL_ERROR
    headers = dict(exc.headers or {})
    return envelope_response(code, default_message_for(code), exc.status_code, headers=headers)


async def unhandled_exception_handler(request: Request, exc: Exception) -> JSONResponse:
    """Anything unhandled -> 500 ``internal_error`` with a generic message.

    The real exception is logged against ``request_id``; it never reaches the
    client.
    """
    logger.exception(
        "unhandled_exception request_id=%s path=%s", current_request_id(), request.url.path
    )
    return envelope_response(
        ErrorCode.INTERNAL_ERROR,
        default_message_for(ErrorCode.INTERNAL_ERROR),
        http_status_for(ErrorCode.INTERNAL_ERROR),
    )


def register_exception_handlers(app: FastAPI) -> None:
    """Install all four handlers. Called before any router is included."""
    app.add_exception_handler(ApiError, api_error_handler)
    app.add_exception_handler(RequestValidationError, validation_error_handler)
    app.add_exception_handler(StarletteHTTPException, http_exception_handler)
    app.add_exception_handler(Exception, unhandled_exception_handler)


#: Reusable OpenAPI ``responses=`` fragment so the generated schema advertises
#: the envelope instead of FastAPI's default error schema (Part 3.0). The
#: Flutter models are read off that schema by a human and a wrong schema costs
#: a day.
def openapi_errors(*codes: ErrorCode) -> dict[int | str, dict[str, Any]]:
    out: dict[int | str, dict[str, Any]] = {}
    for code in codes:
        status = http_status_for(code)
        out.setdefault(
            status,
            {"model": ErrorEnvelope, "description": ""},
        )
        description = out[status]["description"]
        out[status]["description"] = f"{description}, {code.value}".lstrip(", ")
    return out
