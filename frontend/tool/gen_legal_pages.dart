// Writes the public web copies of the legal pages from the same text the app
// shows (lib/models/legal_content.dart):
//
//   web/privacy.html          -> <site>/privacy.html
//   web/terms.html            -> <site>/terms.html
//   web/delete-account.html   -> <site>/delete-account.html
//
// App stores ask for a public privacy-policy URL and (Google Play) a public
// page explaining how to delete an account. Run after changing the text:
//
//   dart run tool/gen_legal_pages.dart
//
// test/legal_pages_test.dart fails if the files fall out of date.
import 'dart:io';

import 'package:tennisimo_ai/models/legal_content.dart';

String _esc(String s) => s
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');

String _sections(List<LegalSection> sections) {
  final StringBuffer out = StringBuffer();
  for (final LegalSection section in sections) {
    out.writeln('<section>');
    out.writeln('<h2>${_esc(section.title)}</h2>');
    final List<String> bullets = <String>[];
    void flush() {
      if (bullets.isEmpty) return;
      out.writeln('<ul>');
      for (final String b in bullets) {
        out.writeln('<li>${_esc(b)}</li>');
      }
      out.writeln('</ul>');
      bullets.clear();
    }

    for (final String p in section.paragraphs) {
      if (p.startsWith('• ')) {
        bullets.add(p.substring(2));
      } else {
        flush();
        out.writeln('<p>${_esc(p)}</p>');
      }
    }
    flush();
    out.writeln('</section>');
  }
  return out.toString();
}

