/// Every generated file, by its path under `frontend/`.
Map<String, String> buildLegalPages() {
  final StringBuffer summary = StringBuffer()
    ..writeln('<div class="summary"><h2>The short version</h2><ul>');
  for (final String line in kPrivacySummary) {
    summary.writeln('<li>${_esc(line)}</li>');
  }
  summary.writeln('</ul></div>');

  const String deletion = '''<section>
<h2>Delete from the app</h2>
<ul>
<li>Open Tennisimo and sign in.</li>
<li>Go to <b>Profile</b> (bottom bar), then <b>Delete account</b>.</li>
<li>Type DELETE and confirm.</li>
</ul>
</section>
<section>
<h2>What is deleted</h2>
<p>Immediately and permanently: every video you uploaded, every swing analysis, score, match and rally, and your login. Nothing is kept afterwards, and it cannot be undone.</p>
</section>
<section>
<h2>Can't sign in?</h2>
<p>Email <a href="mailto:$kSupportEmail">$kSupportEmail</a> from the address on your account and ask for deletion. We will delete it and confirm by email.</p>
</section>''';

  return <String, String>{
    'web/privacy.html':
        _page('Privacy policy', '$summary${_sections(kPrivacyPolicy)}'),
    'web/terms.html': _page('Terms of service', _sections(kTermsOfService)),
    'web/delete-account.html':
        _page('Delete your Tennisimo account', deletion),
  };
}

void main() {
  buildLegalPages().forEach((String path, String html) {
    File(path).writeAsStringSync(html);
    stdout.writeln('wrote $path');
  });
}
